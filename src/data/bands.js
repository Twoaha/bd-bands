export function getBand(id) {
  return bands.find((b) => b.id === id)
}

export function getAllSongs() {
  return bands.flatMap((b) =>
    b.albums.flatMap((a) =>
      a.songs.map((s) => ({
        ...s,
        bandId: b.id,
        bandName: b.name,
        albumTitle: a.title,
        albumId: a.id,
      }))
    )
  )
}
